class XArchive:
    """The capture package on disk, written incrementally.

    Responses go under ``raw/responses/`` verbatim (session material
    removed), the extracted node for each post and user beside them. Media
    is content-addressed so a file referenced by several posts is kept
    once. Exports are appended as records arrive, so an interrupted run
    leaves a readable package.
    """

    POST_FIELDS = [
        "post_id", "author_id", "author_handle", "author_name", "relationship",
        "capture_role", "text", "created_time", "conversation_id",
        "in_reply_to_post_id", "in_reply_to_handle", "permalink_url", "lang",
        "reply_count", "repost_count", "like_count", "quote_count",
        "bookmark_count", "view_count", "media_urls", "media_files", "is_pinned",
        "original_post_id", "original_author_handle", "quoted_post_id",
        "quoted_author_handle", "surface", "source", "target_key",
    ]

    def __init__(self, out_dir: Path):
        self.out_dir = Path(out_dir)
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.raw_dir = self.out_dir / "raw"
        self.responses_dir = self.raw_dir / "responses"
        self.media_dir = self.out_dir / "media"
        self.posts_path = self.out_dir / "x-posts.jsonl"
        self.users_path = self.out_dir / "x-users.json"
        self.media_path = self.out_dir / "x-media.json"
        self.events_path = self.out_dir / "x-events.jsonl"
        self.manifest_path = self.out_dir / "x-manifest.json"
        self.checkpoint_path = self.out_dir / "x-checkpoint.json"
        self.checksums_path = self.out_dir / "checksums.sha256"
        self.posts: dict[str, XPost | dict] = {}
        self.users: dict[str, XUser] = {}
        self.media_index: dict[str, dict] = {}
        self._checksums: dict[str, str] = {}
        self.responses_saved = 0
        self._response_serial = self._next_response_serial()
        self._load_existing()

    def _next_response_serial(self) -> int:
        highest = 0
        if self.responses_dir.is_dir():
            for existing in self.responses_dir.glob("response-*.json"):
                digits = existing.stem.rsplit("-", 1)[-1]
                if digits.isdigit():
                    highest = max(highest, int(digits))
        return highest + 1

    def _load_existing(self) -> None:
        if self.media_path.exists():
            try:
                loaded = json.loads(self.media_path.read_text(encoding="utf-8"))
                if isinstance(loaded, dict):
                    self.media_index = {k: v for k, v in loaded.items() if isinstance(v, dict)}
            except (OSError, json.JSONDecodeError):
                pass
        if self.posts_path.exists():
            with self.posts_path.open(encoding="utf-8") as handle:
                for line in handle:
                    try:
                        row = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if isinstance(row, dict) and row.get("post_id"):
                        self.posts[str(row["post_id"])] = row

    # -- events -------------------------------------------------------------
    def event(self, event: str, **details: object) -> None:
        _append_jsonl(self.events_path, {"time": _iso_now(), "event": event, **details})

    # -- raw ----------------------------------------------------------------
    def save_raw(self, kind: str, name: str, payload: object) -> Path:
        target = self.raw_dir / kind / f"{_safe_name(name)}.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        _atomic_json(target, payload)
        self._checksum(target)
        return target

    def save_response(self, meta: dict, body: bytes) -> str:
        """Keep a response exactly as received; returns its package path."""
        name = f"response-{self._response_serial:06d}.json"
        self._response_serial += 1
        target = self.responses_dir / name
        target.parent.mkdir(parents=True, exist_ok=True)
        safe_body, redacted = redact_body(body, str(meta.get("content_type") or ""))
        _atomic_json(target, {
            **meta, "body_bytes": len(safe_body),
            "body_sha256": hashlib.sha256(safe_body).hexdigest(),
            "redacted_fields": redacted,
            "body": safe_body.decode("utf-8", errors="replace")})
        self._checksum(target)
        self.responses_saved += 1
        return f"raw/responses/{name}"

    # -- records ------------------------------------------------------------
    def add_user(self, user: XUser) -> None:
        self.users[user.user_id] = user
        _atomic_json(self.users_path, {
            uid: _without_raw(asdict(u)) for uid, u in self.users.items()})
        self.save_raw("users", user.handle, user.raw)

    def add_post(self, post: XPost) -> bool:
        current = self.posts.get(post.post_id)
        if current is not None:
            # a post first seen as context and now selected as the target's
            # is the target's; the reverse never demotes
            role = current.capture_role if isinstance(current, XPost) else current.get("capture_role")
            if role == "conversation_context" and post.capture_role == "target":
                self.posts[post.post_id] = post
                if post.raw:
                    self.save_raw("posts", post.post_id, post.raw)
                return True
            return False
        self.posts[post.post_id] = post
        _append_jsonl(self.posts_path, self._post_row(post))
        if post.raw:
            self.save_raw("posts", post.post_id, post.raw)
        return True

    def _post_row(self, post: "XPost | dict") -> dict:
        if isinstance(post, dict):
            return dict(post)
        row = _without_raw(asdict(post))
        row.pop("media", None)
        urls = [m.url for m in post.media]
        row["media_urls"] = urls
        row["media_files"] = [(self.media_index.get(u) or {}).get("file") for u in urls]
        original = post.original_post or {}
        quoted = post.quoted_post or {}
        row["original_post_id"] = original.get("post_id")
        row["original_author_handle"] = original.get("author_handle")
        row["quoted_post_id"] = quoted.get("post_id")
        row["quoted_author_handle"] = quoted.get("author_handle")
        for embedded in (original, quoted):
            for item in embedded.get("media") or []:
                if isinstance(item, dict) and item.get("url"):
                    item["file"] = (self.media_index.get(item["url"]) or {}).get("file")
        row.setdefault("target_key", post.provenance.get("target_key"))
        return row

    # -- media --------------------------------------------------------------
    def save_media(self, url: str, body: bytes, content_type: str = "", *,
                   discovered_from: Optional[str] = None,
                   page_loaded_variant: Optional[str] = None,
                   requested_variant: Optional[str] = None,
                   fetched_url: Optional[str] = None,
                   fetched_via: Optional[str] = None) -> dict:
        existing = self.media_index.get(url)
        if existing:
            return existing
        digest = hashlib.sha256(body).hexdigest()
        name = f"{digest}{_media_suffix(fetched_url or url, content_type)}"
        self.media_dir.mkdir(parents=True, exist_ok=True)
        target = self.media_dir / name
        if not target.exists():
            temporary = target.with_name(name + ".tmp")
            temporary.write_bytes(body)
            temporary.replace(target)
        entry = {"file": name, "sha256": digest, "bytes": len(body),
                 "content_type": content_type or None,
                 "discovered_from": discovered_from,
                 "page_loaded_variant": page_loaded_variant,
                 "requested_variant": requested_variant,
                 "fetched_url": fetched_url or url,
                 "fetch_initiator": "swm",
                 "fetched_via": fetched_via,
                 "browser_fallback": fetched_via == "playwright-api-request"}
        self.media_index[url] = entry
        self._checksums[f"media/{name}"] = digest
        return entry

    # -- fixity -------------------------------------------------------------
    def _checksum(self, path: Path) -> None:
        try:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
        except OSError:
            return
        self._checksums[str(path.relative_to(self.out_dir)).replace("\\", "/")] = digest

    def _referenced_responses(self) -> set[str]:
        refs: set[str] = set()
        for records in (self.posts.values(), self.users.values()):
            for record in records:
                origin = (record.get("provenance") if isinstance(record, dict)
                          else getattr(record, "provenance", None)) or {}
                if isinstance(origin, dict) and origin.get("response"):
                    refs.add(str(origin["response"]))
        for entry in self.media_index.values():
            if entry.get("discovered_from"):
                refs.add(str(entry["discovered_from"]))
        return refs

    def prune_unreferenced_responses(self) -> int:
        """Drop saved responses no kept record was read from.

        The signed-in client fetches the home feed, notifications and
        recommendations beside the target; those responses are in the WARC,
        which replays only with them, but the raw-response store is the
        evidence for kept records and keeps nothing else.
        """
        if not self.responses_dir.is_dir():
            return 0
        keep = self._referenced_responses()
        removed = 0
        for saved in sorted(self.responses_dir.glob("response-*.json")):
            ref = f"raw/responses/{saved.name}"
            if ref in keep:
                continue
            try:
                saved.unlink()
            except OSError:
                continue
            self._checksums.pop(ref, None)
            removed += 1
        self.responses_saved = len(list(self.responses_dir.glob("response-*.json")))
        return removed

    def finalise(self, manifest: dict, checkpoint: dict) -> None:
        _atomic_json(self.media_path, self.media_index)
        temporary = self.posts_path.with_name(self.posts_path.name + ".tmp")
        with temporary.open("w", encoding="utf-8") as handle:
            for post in self.posts.values():
                handle.write(json.dumps(self._post_row(post), ensure_ascii=False) + "\n")
        temporary.replace(self.posts_path)
        self._write_csv(self.out_dir / "x-posts.csv", self.POST_FIELDS,
                        (self._post_row(p) for p in self.posts.values()))
        _atomic_json(self.checkpoint_path, checkpoint)
        _atomic_json(self.manifest_path, manifest)
        for name in ("x-posts.jsonl", "x-posts.csv", "x-users.json",
                     "x-media.json", "x-manifest.json"):
            path = self.out_dir / name
            if path.exists():
                self._checksum(path)
        lines = [f"{digest}  {name}" for name, digest in sorted(self._checksums.items())]
        temporary = self.checksums_path.with_name("checksums.sha256.tmp")
        temporary.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
        temporary.replace(self.checksums_path)

    @staticmethod
    def _write_csv(path: Path, fields: list[str], rows: Iterable[dict]) -> None:
        temporary = path.with_name(path.name + ".tmp")
        with temporary.open("w", encoding="utf-8-sig", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
            writer.writeheader()
            for row in rows:
                current = dict(row)
                for key in ("media_urls", "media_files"):
                    if isinstance(current.get(key), list):
                        current[key] = json.dumps(current[key], ensure_ascii=False)
                writer.writerow(current)
        temporary.replace(path)


def _without_raw(row: dict) -> dict:
    row = dict(row)
    row.pop("raw", None)
    return row


def _safe_name(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", str(value))[:120] or "item"


def _post_id_int(value: object) -> int:
    try:
        return int(str(value))
    except (TypeError, ValueError):
        return 0


