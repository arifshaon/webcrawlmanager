def _whole(value: object, default: int, label: str, low: int, high: int) -> int:
    if value in (None, ""):
        return default
    try:
        number = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{label} must be a whole number.") from exc
    if not low <= number <= high:
        raise ValueError(f"{label} must be between {low:,} and {high:,}.")
    return number


@dataclass
class XCaptureConfig:
    targets: list[str]
    mode: str = "latest_n"
    requested_mode: Optional[str] = None
    from_date: Optional[str] = None
    to_date: Optional[str] = None
    latest_n: int = 100
    consecutive_older: int = 5
    surfaces: tuple[str, ...] = ("posts",)
    search_product: str = "Latest"
    capture_media: bool = True
    keep_reposts: bool = True
    include_conversation: bool = False
    max_replies_per_post: int = 50
    write_warc: bool = False
    end_stall_rounds: int = 3
    prior_newest: dict = field(default_factory=dict)   # key -> {post_id, date}
    continuation_of: Optional[int] = None
    operator: str = "webarc"
    browser_profile_dir: Optional[str] = None
    browser_mode: str = "headed"
    chrome_path: Optional[str] = None

    @classmethod
    def from_dict(cls, raw: dict) -> "XCaptureConfig":
        targets_raw = raw.get("targets")
        if isinstance(targets_raw, str):
            targets_raw = [line for line in re.split(r"[\n,]+", targets_raw)
                           if line.strip()]
        if not isinstance(targets_raw, list) or not targets_raw:
            raise ValueError("Add at least one X handle, profile, post, hashtag or search.")
        product = str(raw.get("search_product") or "Latest")
        if product not in SEARCH_PRODUCTS:
            raise ValueError("search_product must be 'Latest' or 'Top'")
        targets: list[str] = []
        for item in targets_raw:
            target = parse_x_target(item, product)
            if target.url not in targets:
                targets.append(target.url)
        mode = str(raw.get("mode") or "latest_n")
        if mode not in X_MODES:
            raise ValueError(f"Unsupported X capture mode: {mode}")
        browser_mode = str((raw.get("browser") or {}).get("mode")
                           or raw.get("browser_mode") or "headed")
        if browser_mode not in ("headed", "native"):
            raise ValueError("browser must be 'headed' or 'native'")
        from_date = _date_bound(raw.get("from_date"))
        to_date = _date_bound(raw.get("to_date"), end=True)
        if from_date and to_date and from_date > to_date:
            raise ValueError("The From date must be on or before the To date.")
        if mode == "date_range" and not from_date:
            raise ValueError("Date range mode requires a From date.")
        surfaces_raw = raw.get("surfaces") or ["posts"]
        if isinstance(surfaces_raw, str):
            surfaces_raw = [surfaces_raw]
        surfaces = tuple(s for s in X_SURFACES if s in surfaces_raw)
        if not surfaces:
            raise ValueError("Select at least one of Posts, Replies and Media.")
        prior = raw.get("prior_newest") or {}
        if mode == "since_last":
            missing = [u for u in targets
                       if parse_x_target(u, product).kind != "post"
                       and not (prior.get(parse_x_target(u, product).key) or {}).get("post_id")]
            if missing:
                raise ValueError(
                    "No previous capture state exists for "
                    + ", ".join(parse_x_target(u, product).label for u in missing)
                    + ". Run another capture mode first.")
        return cls(
            targets=targets, mode=mode, requested_mode=mode,
            from_date=from_date, to_date=to_date,
            latest_n=_whole(raw.get("latest_n"), 100, "Latest N", 1, 100_000),
            consecutive_older=max(_MAX_PINNED + 1, _whole(
                raw.get("consecutive_older"), 5, "Consecutive older posts", 2, 25)),
            surfaces=surfaces, search_product=product,
            capture_media=bool(raw.get("capture_media", True)),
            keep_reposts=bool(raw.get("keep_reposts", True)),
            include_conversation=bool(raw.get("include_conversation", False)),
            max_replies_per_post=_whole(
                raw.get("max_replies_per_post"), 50, "Maximum replies per post", 1, 5_000),
            write_warc=bool(raw.get("write_warc", False)),
            end_stall_rounds=max(1, _whole(
                raw.get("end_stall_rounds"), 3, "Stall rounds", 1, 20)),
            prior_newest=dict(prior),
            continuation_of=raw.get("continuation_of"),
            operator=str(raw.get("operator") or "webarc"),
            browser_profile_dir=(raw.get("browser_profile_dir")
                                 or (raw.get("browser") or {}).get("user_data_dir")),
            browser_mode=browser_mode,
            chrome_path=(raw.get("browser") or {}).get("chrome_path"),
        )


