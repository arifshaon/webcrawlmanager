_X_HOSTS = {"x.com", "www.x.com", "mobile.x.com", "twitter.com",
            "www.twitter.com", "mobile.twitter.com"}
_HANDLE_RE = re.compile(r"^[A-Za-z0-9_]{1,15}$")
_RESERVED = {
    "home", "explore", "notifications", "messages", "i", "settings", "search",
    "hashtag", "login", "logout", "compose", "intent", "share", "account",
    "tos", "privacy", "about", "jobs", "signup", "flow", "communities",
    "lists", "bookmarks", "premium", "verified-choose",
}


@dataclass(frozen=True)
class XTarget:
    """What a curator asked for, once the text has been read."""
    kind: str                      # "profile" | "post" | "search"
    handle: Optional[str] = None
    post_id: Optional[str] = None
    query: Optional[str] = None
    product: str = "Latest"
    url: str = ""

    @property
    def key(self) -> str:
        if self.kind == "profile":
            return f"x:@{(self.handle or '').lower()}"
        if self.kind == "post":
            return f"x:/{self.post_id}"
        return f"x:search:{self.product.lower()}:{(self.query or '').strip().lower()}"

    @property
    def label(self) -> str:
        if self.kind == "profile":
            return f"@{self.handle}"
        if self.kind == "post":
            return f"post {self.post_id}"
        return f"search \u201c{self.query}\u201d ({self.product})"


def search_url(query: str, product: str = "Latest") -> str:
    tab = {"latest": "live", "top": "top", "media": "media"}.get(product.lower(), "live")
    return f"https://x.com/search?q={quote(query, safe='')}&src=typed_query&f={tab}"


def parse_x_target(raw: object, product: str = "Latest") -> XTarget:
    """Read a handle, a profile URL, a post URL, a hashtag or a search.

    Accepted: ``@handle`` or ``handle``; ``https://x.com/handle`` (with or
    without ``/with_replies`` or ``/media``); ``https://x.com/handle/status/
    <id>``; ``#tag`` or ``https://x.com/hashtag/tag``; ``search:<query>`` or
    a ``https://x.com/search?q=`` URL. twitter.com addresses are read as
    x.com ones. Home, notifications, messages and the rest of the signed-in
    client's own pages are refused: they are the viewer's, not a target.
    """
    text = str(raw or "").strip()
    if not text:
        raise ValueError("Enter an X handle, profile, post, hashtag or search.")
    product = product if product in SEARCH_PRODUCTS else "Latest"
    lowered = text.lower()
    if lowered.startswith("search:"):
        query = text[len("search:"):].strip()
        if not query:
            raise ValueError("A search needs some words after \u201csearch:\u201d.")
        return XTarget("search", query=query, product=product,
                       url=search_url(query, product))
    if text.startswith("#") and "/" not in text and " " not in text:
        tag = text[1:]
        if not re.match(r"^[\w]{1,100}$", tag):
            raise ValueError(f"{text!r} is not a hashtag.")
        return XTarget("search", query=f"#{tag}", product=product,
                       url=search_url(f"#{tag}", product))
    if "://" not in text and "/" not in text and "?" not in text:
        handle = text.lstrip("@")
        if not _HANDLE_RE.match(handle):
            raise ValueError(f"{text!r} is not an X handle: up to 15 letters, "
                             "digits or underscores.")
        if handle.lower() in _RESERVED:
            raise ValueError(f"{handle!r} is one of X's own pages, not an account.")
        return XTarget("profile", handle=handle, url=f"https://x.com/{handle}")
    if "://" not in text:
        text = "https://" + text
    parts = urlsplit(text)
    host = (parts.hostname or "").lower()
    if host not in _X_HOSTS:
        raise ValueError(f"{text} is not an X (or twitter.com) address.")
    segments = [s for s in (parts.path or "/").split("/") if s]
    if not segments:
        raise ValueError("Enter a profile, post, hashtag or search address, "
                         "not X's home page.")
    head = segments[0].lower()
    if head == "search":
        params = parse_qs(parts.query)
        query = (params.get("q") or [""])[0].strip()
        if not query:
            raise ValueError("The search address carries no query (q=).")
        tab = (params.get("f") or ["live"])[0].lower()
        chosen = {"live": "Latest", "top": "Top"}.get(tab, product)
        return XTarget("search", query=query, product=chosen,
                       url=search_url(query, chosen))
    if head == "hashtag" and len(segments) >= 2:
        tag = unquote(segments[1])
        return XTarget("search", query=f"#{tag}", product=product,
                       url=search_url(f"#{tag}", product))
    if head == "i" and len(segments) >= 3 and segments[1] in ("status", "web"):
        post_id = segments[2]
        if not post_id.isdigit():
            raise ValueError(f"{post_id!r} is not a post id.")
        return XTarget("post", post_id=post_id, url=f"https://x.com/i/status/{post_id}")
    if head in _RESERVED:
        raise ValueError(
            f"/{segments[0]}/ is one of X's own pages -- the viewer's home, "
            "notifications, messages or settings -- not an account, a post "
            "or a search.")
    handle = segments[0]
    if not _HANDLE_RE.match(handle):
        raise ValueError(f"{handle!r} is not an X handle.")
    if len(segments) >= 3 and segments[1] == "status":
        post_id = segments[2]
        if not post_id.isdigit():
            raise ValueError(f"{post_id!r} is not a post id.")
        return XTarget("post", handle=handle, post_id=post_id,
                       url=f"https://x.com/{handle}/status/{post_id}")
    if len(segments) > 2 or (len(segments) == 2 and segments[1] not in (
            "with_replies", "media", "highlights", "likes", "articles")):
        raise ValueError(f"/{'/'.join(segments)} is not a profile, post, "
                         "hashtag or search address.")
    return XTarget("profile", handle=handle, url=f"https://x.com/{handle}")


