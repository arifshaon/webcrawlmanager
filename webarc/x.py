"""X (formerly Twitter) capture for SWM.

X is captured as a preservation package, in the same order of primacy as
Instagram's:

1. media as X served it -- the ``orig`` rendition of each image, the
   highest-bitrate progressive MP4 of each video -- with SHA-256 fixity;
2. the untouched responses X returned, under ``raw/``;
3. normalised posts and users as JSONL/CSV;
4. optionally, a WARC of every exchange the browser made, for how X
   presented what was collected;
5. a manifest stating what was asked for, what was reached, what failed and
   what was not attempted.

Collection happens through the browser X serves: a real Chrome, signed in
once by the curator in a dedicated profile, opening a profile, a post or a
search the way a person does. X's own web client builds every request; SWM
recognises the operation from the request's URL and reads the answer. That
sidesteps the three things every reader that builds its own requests spends
its life chasing (rotating operation ids, drifting feature flags, and a
transaction header generated by an obfuscated script), and leaves X's
rate limits and account checks as the conditions they are.

The engine here is written against a client protocol so the collector
(``x_browser``) can be exercised with a stand-in. Framework pieces --
holds, rate-limit waits, checkpoints, the manifest conventions, the
metadata layer -- follow the Instagram mode; the records are X's own:
replies are posts, reposts are kept with the original inside and never
shown as the account's authorship, quotes carry the quoted post, and
other people's posts pulled in to explain a conversation are marked as
context and never counted as the account's.
"""
