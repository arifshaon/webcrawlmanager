class XError(Exception):
    """Base for the conditions the engine has a response to."""


class RateLimited(XError):
    def __init__(self, wait_seconds: float = 300.0, detail: str = ""):
        super().__init__(detail or "X is limiting requests.")
        self.wait_seconds = wait_seconds


class LoginRequired(XError):
    """The session is missing, expired, or not enough for this target."""


class CheckpointRequired(XError):
    """X wants a person: a verification, a lock, a challenge."""


class TargetUnavailable(XError):
    """Not found, suspended, protected and not followed, or not servable."""


class XClient(Protocol):
    """What the engine needs from X, so a test can stand it in.

    Every method returns plain records carrying the untouched payload in
    ``raw``; the client does not decide what to keep.
    """

    def viewer(self) -> Optional[str]: ...
    def user(self, handle: str) -> XUser: ...
    def timeline(self, user: XUser, surface: str) -> Iterator[XPost]: ...
    def post(self, post_id: str) -> XPost: ...
    def conversation(self, post_id: str) -> Iterator[XPost]: ...
    def search(self, query: str, product: str) -> Iterator[XPost]: ...
    def fetch(self, url: str) -> tuple[bytes, str]: ...


