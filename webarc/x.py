class XCaptureSession:
    """Runs one X job: several targets, one at a time.

    ``control_poll`` returns "pause", "resume", "stop" or None; the run
    checks it between posts and while waiting out a rate limit. ``on_progress``
    receives the state and a details dict for the dashboard. ``open_browser``
    is called with a URL when a person is needed and returns a closer.
    """

    def __init__(self, *, config: XCaptureConfig, client: XClient,
                 output_dir: Path, crawl_id: int, crawl_name: str,
                 known_ids: Optional[dict[str, set[str]]] = None,
                 control_poll: Optional[Callable[[], Optional[str]]] = None,
                 on_progress: Optional[Callable[..., None]] = None,
                 persist: Optional[Callable[..., None]] = None,
                 open_browser: Optional[Callable[[str], Callable[[], None]]] = None,
                 sleep: Callable[[float], None] = time.sleep):
        self.config = config
        self.client = client
        self.archive = XArchive(output_dir)
        self.crawl_id = crawl_id
        self.crawl_name = crawl_name
        self.known_ids = known_ids or {}
        self.control_poll = control_poll or (lambda: None)
        self.on_progress = on_progress or (lambda **_kw: None)
        self.persist = persist or (lambda **_kw: None)
        self.open_browser = open_browser
        self.sleep = sleep

        self.state = RECORDING
        self.phase_detail = "Starting."
        self.stop_reason: Optional[str] = None
        self.stop_rule: Optional[str] = None
        self.counters: Counter = Counter()
        self.exclusions: Counter = Counter()
        self.targets = [parse_x_target(u, config.search_product) for u in config.targets]
        self.target_status: dict[str, dict] = {
            t.key: {"label": t.label, "kind": t.kind, "status": "pending",
                    "posts_selected": 0, "posts_encountered": 0}
            for t in self.targets}
        self.target_ids: dict[str, str] = {}
        self._anomalies_drained = 0
        self.current_target: Optional[XTarget] = None
        self._stop_requested = False
        self._rate_limit_streak = 0
        self._last_report = 0.0
        self.viewer_id: Optional[str] = None
        self.newest_by_target: dict[str, dict] = {}
        self.absences: list[dict] = []

    # -- control ------------------------------------------------------------
    def _check_control(self) -> None:
        command = self.control_poll()
        if command == CMD_STOP:
            self._request_stop("curator_stop", "curator_selected_stop_and_save")
            return
        if command == CMD_PAUSE:
            self.state = PAUSED
            self.phase_detail = "Paused. Nothing further is requested from X until you resume."
            self.archive.event("paused", actor="dashboard")
            self._report(force=True)
            while True:
                self.sleep(1.0)
                command = self.control_poll()
                if command == CMD_STOP:
                    self._request_stop("curator_stop", "curator_selected_stop_and_save")
                    return
                if command == CMD_RESUME:
                    self.state = RECORDING
                    self.phase_detail = "Resumed."
                    self.archive.event("resumed", actor="dashboard")
                    self._report(force=True)
                    return

    def _request_stop(self, reason: str, rule: str) -> None:
        if not self._stop_requested:
            self._stop_requested = True
            self.stop_reason, self.stop_rule = reason, rule
            self.archive.event("stopping_rule_fired", reason=reason, rule=rule)

    def _hold_for_curator(self, why: str, url: str) -> bool:
        self.state = BLOCKED
        self.phase_detail = why
        self.archive.event("curator_needed", reason=why, url=url)
        self._report(force=True)
        close = None
        if self.open_browser is not None:
            try:
                close = self.open_browser(url)
            except Exception as exc:
                log.warning("Could not open the browser for the curator: %s", exc)
        try:
            while True:
                self.sleep(1.0)
                command = self.control_poll()
                if command == CMD_STOP:
                    self._request_stop("curator_stop", "curator_selected_stop_and_save")
                    return False
                if command == CMD_RESUME:
                    self.state = RECORDING
                    self.phase_detail = "Continuing."
                    self.archive.event("curator_resolved")
                    self._report(force=True)
                    return True
        finally:
            if close is not None:
                try:
                    close()
                except Exception:
                    pass

    def _wait_out_rate_limit(self, exc: RateLimited) -> bool:
        """Sit out a limit until the reset X named, still answering Stop."""
        self._rate_limit_streak += 1
        wait = float(exc.wait_seconds)
        if wait <= 0:
            wait = 60.0 * (2 ** (self._rate_limit_streak - 1))
        wait = max(20.0, min(wait, 960.0))
        self.counters["rate_limit_waits"] += 1
        self.archive.event("rate_limited", wait_seconds=wait,
                           streak=self._rate_limit_streak, detail=str(exc))
        remaining = wait
        while remaining > 0:
            self.phase_detail = (f"X is limiting requests. Waiting "
                                 f"{int(remaining)}s before continuing.")
            self._report(force=True)
            step = min(5.0, remaining)
            self.sleep(step)
            remaining -= step
            if self.control_poll() == CMD_STOP:
                self._request_stop("curator_stop", "curator_selected_stop_and_save")
                return False
        return True

    def _with_retries(self, action: Callable[[], object], url: str, what: str) -> object:
        for _attempt in range(6):
            if self._stop_requested:
                raise TargetUnavailable("stopped")
            try:
                result = action()
                self._rate_limit_streak = 0
                return result
            except RateLimited as exc:
                if not self._wait_out_rate_limit(exc):
                    raise TargetUnavailable("stopped") from exc
            except LoginRequired as exc:
                if not self._hold_for_curator(
                        f"X needs you to sign in before {what}: {exc}. Sign in "
                        "in the browser window that has opened, then select "
                        "\u201cI have resolved it \u2014 continue\u201d.", url):
                    raise TargetUnavailable("stopped") from exc
                self._refresh_client()
            except CheckpointRequired as exc:
                if not self._hold_for_curator(
                        f"X is asking for verification before {what}: {exc}. "
                        "Resolve it in the browser window that has opened, then "
                        "select \u201cI have resolved it \u2014 continue\u201d.", url):
                    raise TargetUnavailable("stopped") from exc
                self._refresh_client()
        raise TargetUnavailable(f"{what} did not succeed after repeated tries.")

    def _refresh_client(self) -> None:
        refresh = getattr(self.client, "refresh", None)
        if callable(refresh):
            try:
                refresh()
            except Exception as exc:
                log.warning("Session refresh failed: %s", exc)

    # -- progress -----------------------------------------------------------
    def _report(self, force: bool = False) -> None:
        now = time.monotonic()
        if not force and now - self._last_report < 1.0:
            return
        self._last_report = now
        try:
            self.on_progress(state=self.state,
                             visited=self._count_role("target"),
                             failed=self.counters.get("posts_failed", 0),
                             current_url=(self.current_target.url
                                          if self.current_target else None),
                             details=self._progress_details())
        except Exception as exc:
            log.debug("Progress report failed: %s", exc)

    def _rows(self) -> Iterator[dict]:
        for post in self.archive.posts.values():
            yield self.archive._post_row(post) if isinstance(post, XPost) else post

    def _count_role(self, role: str) -> int:
        return sum(1 for row in self._rows() if row.get("capture_role") == role)

    def _count_relationship(self, relationship: str) -> int:
        return sum(1 for row in self._rows()
                   if row.get("capture_role") == "target"
                   and row.get("relationship") == relationship)

    def _progress_details(self) -> dict:
        done = sum(1 for t in self.target_status.values()
                   if t["status"] in ("done", "failed", "unavailable"))
        dates = [row.get("created_time") for row in self._rows()
                 if row.get("capture_role") == "target" and row.get("created_time")]
        return {
            "phase": ("finished" if self.state == STOPPED
                      else "verification_required" if self.state == BLOCKED
                      else "collecting" if self.state == RECORDING
                      else "paused"),
            "message": self.phase_detail,
            "viewer": self.viewer_id or "signed_out",
            "targets_total": len(self.targets),
            "targets_done": done,
            "current_target": self.current_target.label if self.current_target else None,
            "posts_encountered": self.counters.get("posts_encountered", 0),
            "posts_exported": self._count_role("target"),
            "reposts_exported": self._count_relationship("repost"),
            "context_posts": self._count_role("conversation_context"),
            "replies_exported": self.counters.get("replies_collected", 0),
            # an account is a record of its own: a profile with no posts is
            # still captured, and its pages still open
            "users_exported": len(self.archive.users),
            "media_expected": self.counters.get("media_expected", 0),
            "media_captured": len(self.archive.media_index),
            "media_failed": self.counters.get("media_failed", 0),
            "newest_post": max(dates) if dates else None,
            "oldest_post": min(dates) if dates else None,
            "rate_limit_waits": self.counters.get("rate_limit_waits", 0),
            "warc_files": self.counters.get("warc_files") or len(
                list(self.archive.out_dir.glob("*.warc.gz"))),
            "targets": list(self.target_status.values()),
        }

    # -- the run --------------------------------------------------------------
    def run(self) -> dict:
        self.archive.event("capture_created", mode=self.config.mode,
                           targets=[t.url for t in self.targets],
                           continuation_of=self.config.continuation_of)
        record_responses = getattr(self.client, "record_responses_to", None)
        if callable(record_responses):
            record_responses(self.archive.save_response)
        attach_controls = getattr(self.client, "attach_engine_controls", None)
        if callable(attach_controls):
            attach_controls(self._check_control, lambda: self._stop_requested)
        if not self._establish_viewer():
            return self._finish()

        for target in self.targets:
            if self._stop_requested:
                break
            self.current_target = target
            status = self.target_status[target.key]
            status["status"] = "running"
            self.phase_detail = f"Collecting {target.label}."
            self._report(force=True)
            try:
                if target.kind == "profile":
                    self._capture_profile(target)
                elif target.kind == "post":
                    self._capture_single(target)
                else:
                    self._capture_search(target)
                if not self._stop_requested:
                    status["status"] = "done"
            except TargetUnavailable as exc:
                if str(exc) == "stopped":
                    status["status"] = "interrupted"
                    break
                status["status"] = "unavailable"
                status["reason"] = str(exc)
                self.counters["targets_unavailable"] += 1
                self.archive.event("target_unavailable", target=target.url, reason=str(exc))
            except XError as exc:
                status["status"] = "failed"
                status["reason"] = str(exc)
                self.counters["targets_failed"] += 1
                self.archive.event("target_failed", target=target.url, error=str(exc))
            finally:
                self._drain_client_anomalies()
                self._checkpoint()
        self.current_target = None
        if not self._stop_requested:
            self.stop_reason = self.stop_reason or "targets_complete"
            self.stop_rule = self.stop_rule or "every_target_worked"
        return self._finish()

    def _finish(self) -> dict:
        self.state = STOPPED
        self.phase_detail = self._closing_summary()
        self.archive.prune_unreferenced_responses()
        self.archive.finalise(self.manifest_document(final=True), self._checkpoint_document())
        self._report(force=True)
        try:
            self.persist(targets=self.newest_by_target, posts=list(self._rows()),
                         users=self.archive.users)
        except Exception as exc:
            log.warning("Could not persist capture state: %s", exc)
        return {"stop_reason": self.stop_reason, "stop_rule": self.stop_rule,
                "posts": self._count_role("target"),
                "context_posts": self._count_role("conversation_context"),
                "media": len(self.archive.media_index)}

    def _establish_viewer(self) -> bool:
        """A signed-in session is the product requirement.

        The browser opens for the curator on X's own sign-in page when the
        profile is not signed in. A curator who continues still signed out
        has decided; the run goes on and the manifest says what that bounds.
        """
        for attempt in range(3):
            try:
                self.viewer_id = self.client.viewer()
            except XError as exc:
                log.info("Viewer unknown: %s", exc)
                self.viewer_id = None
            if self.viewer_id:
                break
            still = " still" if attempt else ""
            held = self._hold_for_curator(
                f"The capture browser is{still} not signed in to X. Sign in in "
                "the window that has opened -- use a dedicated institutional "
                "account, not a personal one -- then select \u201cI have "
                "resolved it \u2014 continue\u201d. SWM reads the session from "
                "that browser profile; it never sees the password.",
                "https://x.com/i/flow/login")
            if not held:
                return False
            self._refresh_client()
            if attempt == 2:
                self.archive.event("proceeding_signed_out")
        self.archive.event("viewer", user_id=self.viewer_id, signed_in=bool(self.viewer_id))
        self._report(force=True)
        return True

    def _closing_summary(self) -> str:
        posts = self._count_role("target")
        context = self._count_role("conversation_context")
        media = len(self.archive.media_index)
        accounts = len(self.archive.users)
        because = {
            "targets_complete": "every target was worked",
            "curator_stop": "you selected Stop and save",
        }.get(self.stop_reason or "", str(self.stop_reason or "").replace("_", " "))
        return (f"Collected {accounts} account{'s' if accounts != 1 else ''}, "
                f"{posts} post{'s' if posts != 1 else ''}, "
                f"{context} context post{'s' if context != 1 else ''}, "
                f"{media} media file{'s' if media != 1 else ''}. "
                f"Stopped because {because}.")

    def _drain_client_anomalies(self) -> None:
        anomalies = getattr(self.client, "anomalies", None)
        if not isinstance(anomalies, list):
            return
        for anomaly in anomalies[self._anomalies_drained:]:
            if isinstance(anomaly, dict):
                self.archive.event("client_anomaly", **anomaly)
        self._anomalies_drained = len(anomalies)

    # -- a single post ----------------------------------------------------------
    def _capture_single(self, target: XTarget) -> None:
        post = self._with_retries(lambda: self.client.post(target.post_id or ""),
                                  target.url, f"reading {target.label}")
        assert isinstance(post, XPost)
        post.surface = "direct"
        post.capture_role = "target"
        self.counters["posts_encountered"] += 1
        self.target_status[target.key]["posts_encountered"] += 1
        if post.author_id:
            self.target_ids[target.key] = post.author_id
        self._take_post(post, target, conversation=True)

    # -- a profile --------------------------------------------------------------
    def _capture_profile(self, target: XTarget) -> None:
        handle = target.handle or ""
        user = self._with_retries(lambda: self.client.user(handle), target.url,
                                  f"reading {target.label}")
        assert isinstance(user, XUser)
        self.archive.add_user(user)
        self.target_ids[target.key] = user.user_id
        self.target_status[target.key]["user_id"] = user.user_id
        self.target_status[target.key]["handle"] = user.handle
        if user.is_protected and not self.viewer_id:
            raise TargetUnavailable(
                f"{target.label} is protected, and the capture browser is not "
                "signed in to an account that follows it.")
        if self.config.capture_media and user.profile_image_url:
            self._fetch_one(user.profile_image_url, f"profile image of {target.label}",
                            discovered_from=user.provenance.get("response"),
                            page_loaded_variant="as served", requested_variant="as served")
        seen: set[str] = set()
        for surface in self.config.surfaces:
            if self._stop_requested:
                return
            iterator = self.client.timeline(user, surface)
            try:
                self._walk_listing(target, surface, iterator, seen, user)
            finally:
                close = getattr(iterator, "close", None)
                if callable(close):
                    close()
            self._drain_client_anomalies()

    # -- a search ------------------------------------------------------------------
    def _capture_search(self, target: XTarget) -> None:
        iterator = self.client.search(target.query or "", target.product)
        try:
            self._walk_listing(target, "search", iterator, set(), None)
        finally:
            close = getattr(iterator, "close", None)
            if callable(close):
                close()

    def _is_targets_own(self, post: XPost, target: XTarget) -> bool:
        """The numeric id decides; the handle only where no id is known."""
        if target.kind != "profile":
            return True
        wanted_id = self.target_ids.get(target.key)
        if post.author_id and wanted_id:
            return str(post.author_id) == str(wanted_id)
        return (post.author_handle or "").lower() == (target.handle or "").lower()

    def _walk_listing(self, target: XTarget, surface: str, iterator: Iterator[XPost],
                      seen: set[str], user: Optional[XUser]) -> None:
        status = self.target_status[target.key]
        consecutive_older = 0
        prior = self.config.prior_newest.get(target.key) or {}
        pinned_ids = set(user.pinned_post_ids) if user else set()

        while True:
            if self._stop_requested:
                return
            try:
                post = self._with_retries(lambda: next(iterator), target.url,
                                          f"listing {target.label} {surface}")
            except TargetUnavailable:
                raise
            except StopIteration:
                break
            if not isinstance(post, XPost):
                break
            self._check_control()
            if self._stop_requested:
                return
            self.counters["posts_encountered"] += 1
            status["posts_encountered"] += 1
            if not self._is_targets_own(post, target):
                self.counters["foreign_posts_skipped"] += 1
                self.archive.event("foreign_post_skipped", target=target.label,
                                   post_id=post.post_id, author=post.author_handle)
                continue
            if post.post_id in pinned_ids:
                post.is_pinned = True
            post.surface = surface
            post.capture_role = "target"
            if post.post_id in seen:
                self.exclusions["duplicate_across_surfaces"] += 1
                continue
            seen.add(post.post_id)
            if post.relationship == "repost" and not self.config.keep_reposts:
                self.exclusions["reposts_not_requested"] += 1
                continue

            decision = self._decide(post, prior, target)
            if decision == "select":
                self._take_post(post, target, conversation=self.config.include_conversation)
                if not post.is_pinned:
                    consecutive_older = 0
            elif decision == "older":
                self.exclusions["older_than_requested"] += 1
                if not post.is_pinned:
                    consecutive_older += 1
            elif decision == "newer":
                self.exclusions["newer_than_requested"] += 1
            elif decision == "already_captured":
                self.exclusions["captured_previously"] += 1
                if not post.is_pinned:
                    consecutive_older += 1
            if self._boundary_reached(consecutive_older, self._selected_non_pinned(target)):
                return
        if status["posts_encountered"] == 0:
            self.archive.event("timeline_empty", target=target.url, surface=surface)
            status["empty_surfaces"] = sorted(set(status.get("empty_surfaces", [])) | {surface})
        if self.config.mode in ("until_stopped", "end_of_timeline"):
            self.archive.event("timeline_stalled", target=target.url, surface=surface,
                               posts_encountered=status["posts_encountered"])
            if self.config.mode == "end_of_timeline":
                self._request_stop("timeline_stalled", "no_unseen_posts_after_stall_rounds")

    def _decide(self, post: XPost, prior: dict, target: XTarget) -> str:
        mode = self.config.mode
        when = post.created_time or ""
        if mode == "date_range":
            if self.config.to_date and when and when > self.config.to_date:
                return "newer"
            if self.config.from_date and when and when < self.config.from_date:
                return "older"
            return "select"
        if mode == "latest_n":
            if post.is_pinned:
                return "select"
            # the count is the target's across its surfaces: the newest N
            # posts of the account, not N per tab
            return ("select" if self._selected_non_pinned(target) < self.config.latest_n
                    else "older")
        if mode == "since_last":
            # the pinned post sits first whatever its age; only a post
            # already captured is passed over, never one that is merely old
            if post.post_id in self.known_ids.get(target.key, set()):
                return "already_captured"
            if post.is_pinned:
                return "select"
            newest_id = _post_id_int(prior.get("post_id"))
            newest_date = str(prior.get("date") or "")
            if _post_id_int(post.post_id) and newest_id and _post_id_int(post.post_id) <= newest_id:
                return "already_captured"
            if newest_date and when and when <= newest_date:
                return "already_captured"
            return "select"
        return "select"

    def _selected_non_pinned(self, target: XTarget) -> int:
        status = self.target_status[target.key]
        return status["posts_selected"] - status.get("pinned_selected", 0)

    def _boundary_reached(self, consecutive_older: int, selected: int) -> bool:
        mode = self.config.mode
        if mode in ("date_range", "since_last"):
            if consecutive_older >= self.config.consecutive_older:
                self.archive.event("lower_boundary_reached", consecutive_older=consecutive_older)
                return True
        if mode == "latest_n" and selected >= self.config.latest_n:
            return True
        return False

    # -- one post's package -------------------------------------------------------
    def _take_post(self, post: XPost, target: XTarget, *, conversation: bool) -> None:
        post.provenance = {**post.provenance, "target_key": target.key}
        added = self.archive.add_post(post)
        if not added:
            return
        status = self.target_status[target.key]
        status["posts_selected"] += 1
        if post.is_pinned:
            status["pinned_selected"] = status.get("pinned_selected", 0) + 1
        self._track_newest(target, post)
        if self.config.capture_media:
            self._collect_media(post)
        self._collect_listing_context(post, target)
        if conversation and post.relationship != "repost":
            self._collect_conversation(post, target)
        self.phase_detail = (
            f"Collecting {target.label}: {self._count_role('target')} posts, "
            f"{len(self.archive.media_index)} media files"
            + (f", {self._count_role('conversation_context')} context posts"
               if conversation else "") + ".")
        self._report()
        if len(self.archive.posts) % 10 == 0:
            self._checkpoint()

    def _track_newest(self, target: XTarget, post: XPost) -> None:
        if post.is_pinned or target.kind == "post":
            return
        current = self.newest_by_target.get(target.key) or {}
        if not current or _post_id_int(post.post_id) > _post_id_int(current.get("post_id")):
            self.newest_by_target[target.key] = {
                "post_id": post.post_id, "date": post.created_time,
                "handle": target.handle, "user_id": self.target_ids.get(target.key),
                "url": target.url}

    def _collect_listing_context(self, post: XPost, target: XTarget) -> None:
        """Other people's posts the listing showed beside this one (a
        thread module on the Replies tab) are context, kept as such."""
        neighbours = getattr(self.client, "conversation_context", None)
        if not callable(neighbours) or not post.conversation_id:
            return
        try:
            found = neighbours(post.post_id)
        except Exception as exc:
            log.debug("Context lookup failed: %s", exc)
            return
        for other in found or []:
            if not isinstance(other, XPost) or other.post_id == post.post_id:
                continue
            if self._is_targets_own(other, target) and target.kind == "profile":
                continue          # the account's own posts are listed on their own
            other.capture_role = "conversation_context"
            other.surface = post.surface
            other.provenance = {**other.provenance, "target_key": target.key,
                                "context_for": post.post_id}
            if self.archive.add_post(other):
                self.counters["context_posts"] += 1
                if self.config.capture_media:
                    self._collect_media(other)

    def _media_of(self, post: XPost) -> list[tuple[XMediaItem, str]]:
        items = [(m, "post") for m in post.media]
        for kind, embedded in (("original_post", post.original_post),
                               ("quoted_post", post.quoted_post)):
            for entry in (embedded or {}).get("media") or []:
                if isinstance(entry, dict) and entry.get("url"):
                    already = any(m.url == entry["url"] for m, _ in items)
                    if not already:
                        items.append((XMediaItem(
                            url=str(entry["url"]), kind=str(entry.get("kind") or "image"),
                            position=int(entry.get("position") or 0),
                            page_url=entry.get("page_url"),
                            requested_variant=str(entry.get("requested_variant") or "orig")),
                            kind))
        return items

    def _collect_media(self, post: XPost) -> None:
        for item, part in self._media_of(post):
            self.counters["media_expected"] += 1
            if item.url in self.archive.media_index:
                continue
            self._fetch_one(item.url, f"downloading media for {post.post_id}",
                            discovered_from=post.provenance.get("response"),
                            page_loaded_variant=item.page_url,
                            requested_variant=item.requested_variant,
                            fallbacks=list(item.fallback_urls), post_id=post.post_id,
                            part=part)

    def _fetch_one(self, url: str, what: str, *, discovered_from: Optional[str],
                   page_loaded_variant: Optional[str], requested_variant: Optional[str],
                   fallbacks: Optional[list[str]] = None, post_id: Optional[str] = None,
                   part: str = "post") -> Optional[dict]:
        candidates = [url] + [f for f in (fallbacks or []) if f != url]
        last_error = "empty response"
        for candidate in candidates:
            try:
                body, content_type = self._with_retries(
                    lambda: self.client.fetch(candidate), candidate, what)
            except TargetUnavailable as exc:
                if str(exc) == "stopped":
                    return None
                last_error = str(exc)
                continue
            except XError as exc:
                last_error = str(exc)
                continue
            if not body:
                continue
            variant = requested_variant
            if candidate != url:
                variant = f"{requested_variant} refused; fell back to {candidate}"
                self.archive.event("media_fallback", post_id=post_id, requested=url,
                                   served=candidate)
            return self.archive.save_media(
                url, body, content_type, discovered_from=discovered_from,
                page_loaded_variant=page_loaded_variant, requested_variant=variant,
                fetched_url=candidate,
                fetched_via=getattr(self.client, "last_fetch_via", None))
        self.counters["media_failed"] += 1
        self.archive.event("media_failed", post_id=post_id, url=url, part=part,
                           error=last_error)
        return None

    def _collect_conversation(self, post: XPost, target: XTarget) -> None:
        """The post's page: what it replies to, and the replies under it.

        Replies are posts with their own ids and authors, kept as context
        (they are not the account's), up to the cap; the ancestors the post
        replies to are context too. The outcome is graded per post the way
        the Instagram mode grades comments.
        """
        wanted = self.config.max_replies_per_post
        replies = 0
        stop_reason = "exhausted"
        try:
            iterator = self._with_retries(
                lambda: self.client.conversation(post.post_id), post.permalink_url or "",
                f"reading the conversation of {post.post_id}")
            for other in iterator:      # type: ignore[union-attr]
                if self._stop_requested:
                    stop_reason = "stopped"
                    return
                if not isinstance(other, XPost) or other.post_id == post.post_id:
                    continue
                # a direct reply, or -- when the post is its conversation's
                # root -- anything later in that conversation
                is_reply = (other.in_reply_to_post_id == post.post_id or
                            (post.conversation_id == post.post_id
                             and other.conversation_id == post.post_id
                             and _post_id_int(other.post_id) > _post_id_int(post.post_id)))
                if is_reply:
                    if replies >= wanted:
                        self.exclusions["reply_limit_reached"] += 1
                        stop_reason = "reply_limit_reached"
                        break
                    replies += 1
                other.capture_role = "conversation_context"
                other.surface = "conversation"
                other.provenance = {**other.provenance, "target_key": target.key,
                                    "context_for": post.post_id}
                if self.archive.add_post(other):
                    self.counters["context_posts"] += 1
                    if is_reply:
                        self.counters["replies_collected"] += 1
                    if self.config.capture_media:
                        self._collect_media(other)
        except TargetUnavailable as exc:
            if str(exc) == "stopped":
                stop_reason = "stopped"
                return
            stop_reason = "failed"
            self.counters["conversations_failed"] += 1
            self.archive.event("conversation_failed", post_id=post.post_id, error=str(exc))
        except XError as exc:
            stop_reason = "failed"
            self.counters["conversations_failed"] += 1
            self.archive.event("conversation_failed", post_id=post.post_id, error=str(exc))
        finally:
            self._note_absences(post)
            self._grade_conversation(post, replies, stop_reason)

    def _note_absences(self, post: XPost) -> None:
        absences = getattr(self.client, "absences", None)
        if not callable(absences):
            return
        try:
            found = absences(post.post_id)
        except Exception:
            return
        for absence in found or []:
            if isinstance(absence, XAbsence):
                record = {"conversation_of": post.post_id, "kind": absence.kind,
                          "reason": absence.reason, "post_id": absence.post_id,
                          "entry_id": absence.entry_id}
                self.absences.append(record)
                self.archive.event("post_unavailable", **record)

    def _grade_conversation(self, post: XPost, observed: int, stop_reason: str) -> None:
        reported = post.reply_count if isinstance(post.reply_count, int) else None
        more_pages = getattr(self.client, "conversation_more", lambda: None)()
        if stop_reason == "stopped":
            status = "stopped_by_curator"
        elif stop_reason == "failed":
            status = "partial"
        elif reported == 0 and observed == 0:
            status = "no_replies_reported"
        elif stop_reason == "reply_limit_reached":
            status = "capped"
        elif reported is not None and observed >= reported:
            # X's conversation page always offers a cursor; a count that is
            # reached is reached whatever the page still offers
            status = "reported_count_reached"
        elif more_pages is True or reported is not None:
            status = "partial"
        else:
            status = "exhausted_unverified"
        post.reply_capture = {
            "status": status, "observed": observed, "reported": reported,
            "more_pages_seen": more_pages, "stop_reason": stop_reason,
            "cap": self.config.max_replies_per_post,
        }
        self.counters[f"replies_{status}"] += 1

    def _reply_statuses(self) -> dict:
        statuses: Counter = Counter()
        for row in self._rows():
            capture = row.get("reply_capture") or {}
            if capture.get("status"):
                statuses[capture["status"]] += 1
        return dict(statuses)

